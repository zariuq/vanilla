language(anbn_uo_bin,              binary_cgnf,    binary_anbn_uo_range).
language(anbm_bin,                 binary_cgnf,    binary_anbm_range).
language(palindrome_bin,           binary_cgnf,    binary_palindrome_range).
language(parens_bin,               binary_cgnf,    binary_parens_range).
language(dragon_curve,             exp_script_lnf, dragon_curve_generator).
language(hilbert_curve_no_tabling, exp_script_lnf, hilbert_curve_generator).
