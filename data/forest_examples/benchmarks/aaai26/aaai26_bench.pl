/*  Poker against the provenance forest on the experiments of Patsantzis,
    "Self-Supervised Inductive Logic Programming", AAAI-26.

    Source of the benchmark: the paper's code appendix,
    https://github.com/stassa/aaai_26_experiments (commit a446fca). Its ten
    languages are the six binary context-free languages of
    data/experiments/experiment_script_binary_cgnf.pl (weak C-GNF) and the four
    L-systems of data/experiments/experiment_script_lnf.pl (LNF).

    This file contains none of that repository's code. It runs against a
    working copy of the repository made by setup_aaai26.sh (Poker selected as
    the learner and the experiment script chosen, as the repository's README
    describes) and reads every setting from the repository itself: each
    language's configuration from set_configs/2, and its labelled examples,
    testing examples and numbers of generated examples from the arguments its
    range experiment (binary_*_range/3, *_generator/3) passes to
    setup_range_experiments/12, captured before any experiment runs. Examples
    are generated by the repository's generate_initial/3, under a fixed seed.

    Commands (ROOT is the working copy; LANG is one of language/3 below):

      swipl aaai26_bench.pl ROOT settings LANG
          print the captured settings
      swipl aaai26_bench.pl ROOT gen LANG ITER SEEDS LIMIT
          generalisation step: Poker's generalise/3 and the forest's
          forest_generalise/3 on the labelled examples of iteration ITER
          (1-based, or all) of the experiment's range, for each seed in
          SEEDS (a Prolog list), each limited to LIMIT seconds
      swipl aaai26_bench.pl ROOT learn LANG ITER GEN SEEDS LIMIT
          Poker's learn/7 with Vanilla's generalisation and with the forest's,
          GEN generated examples (unlabelled_examples): a number, min or max
          of the range, own (the language's setting), or a list of these; ITER may also be last, a list,
          or calibration (the language's calibration experiment)
      swipl aaai26_bench.pl ROOT tune LANG SEEDS LIMIT KMAX
          (KMAX a number, or her+N: N more than the language's clause limit)
          on the language's calibration experiment, the iterative deepening
          of clause_limit and max_invented from (1,0) until a correct
          hypothesis, with Poker, with the forest run at each candidate, and
          with the forest's read-off
      swipl aaai26_bench.pl ROOT readoff LANG ITER SEEDS LIMIT KMAX MMAX
          the forest's read-off of every smaller (clause_limit, max_invented)
          from one run at (KMAX, MMAX), checked against direct runs of the
          forest and of Poker (KMAX her or her+N: the language's own limits,
          or N more of each, MMAX then ignored)

    Each result is printed as one Prolog term row(...) on standard output.
*/

:- module(aaai26_bench, []).

:- initialization(main, main).

:- discontiguous command/2.

:- dynamic bench_dir/1.
:- prolog_load_context(directory, Dir),
   retractall(bench_dir(_)),
   assertz(bench_dir(Dir)).

:- use_module(library(prolog_wrap)).
:- use_module(library(time)).
:- use_module(library(apply)).
:- use_module(library(lists)).

