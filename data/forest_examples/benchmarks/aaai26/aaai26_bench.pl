main :-
    current_prolog_flag(argv, [Root, Cmd|Args]),
    load_repository(Root),
    load_forest,
    quiet,
    (   catch(command(Cmd, Args), E, (print_message(error, E), halt(1)))
    ->  true
    ;   format(user_error, "Failed: ~w ~w~n", [Cmd, Args]),
        halt(1)
    ).

load_repository(Root) :-
    atomic_list_concat([Root, '/load_headless'], Loader),
    consult(user:Loader),
    (   configuration:learner(poker, _)
    ->  true
    ;   format(user_error, "Select Poker in ~w/configuration.pl~n", [Root]),
        halt(2)
    ).

load_forest :-
    bench_dir(Dir),
    atomic_list_concat([Dir, '/../../../../lib/forest/forest_poker'], F),
    use_module(F).

% The experiment scripts switch on debugging topics; their messages are
% switched off so that neither learner pays for printing.
quiet :-
    forall(debugging(Topic, true), nodebug(Topic)).

% ---------- the settings, read from the repository ----------

%!  settings(+Lang, -Settings) is det.
%
%   Settings is s(Target, Generated, Labelled, Unlabelled, TestPos, TestNeg,
%   TestGen, TableSpace): the arguments the range experiment of Lang passes
%   to setup_range_experiments/12, and the table space in force when it does.
settings(Lang, s(T, Gs, Sl, Su, TPos, TNeg, TGen, TS)) :-
    language(Lang, Script, Range),
    loaded_script(Script),
    Head = experiment_output:setup_range_experiments(_, L, _, T0, _, Gs0, Sl0,
                                                     Su0, TP0, TN0, TG0, _),
    wrap_predicate(Head, aaai26_capture, _Inner,
                   (   current_prolog_flag(table_space, TS0),
                       throw(aaai26_captured(L, T0, Gs0, Sl0, Su0, TP0, TN0,
                                             TG0, TS0))
                   )),
    Goal =.. [Range, 1, user_output, false],
    catch(experiment_file:Goal,
          aaai26_captured(Lang1, T, Gs, Sl, Su, TPos, TNeg, TGen, TS),
          true),
    unwrap_predicate(experiment_output:setup_range_experiments/12,
                     aaai26_capture),
    must_be(oneof([Lang]), Lang1).

loaded_script(Script) :-
    poker_configuration:experiment_file(_, M),
    (   M == Script
    ->  true
    ;   format(user_error,
               "The working copy loads ~w; this language needs ~w~n",
               [M, Script]),
        halt(2)
    ).

%!  configure(+Lang, -Settings) is det.
%
%   Configure Poker for Lang as the range experiment does: set_configs/1
%   (the language's options and safe_example/1) and the table space.
configure(Lang, S) :-
    settings(Lang, S),
    S = s(_, _, _, _, _, _, _, TS),
    set_prolog_flag(table_space, TS),
    experiment_output:set_configs(Lang).

%!  calibration(?Lang, ?Experiment)
%
%   The single experiment of each language that the repository's README
%   describes as used to calibrate the learners' settings before the range
%   experiments.
calibration(even_bin,                 binary_parity).
calibration(anbn_bin,                 binary_anbn).
calibration(anbn_uo_bin,              binary_anbn_uo).
calibration(anbm_bin,                 binary_anbm).
calibration(palindrome_bin,           binary_palindrome).
calibration(parens_bin,               binary_parens).
calibration(dragon_curve,             dragon_curve).
calibration(hilbert_curve_no_tabling, hilbert_curve).
calibration(koch_curve,               koch_curve).
calibration(sierpinski_triangle,      sierpinski_triangle).

%!  configure_calibration(+Lang, -Settings) is det.
%
%   As configure/2, from the arguments the calibration experiment of Lang
%   passes to setup_experiment/8: Settings is s(Target, none, Labelled,
%   Unlabelled, TestPos, TestNeg, TestGen, TableSpace). The number of
%   generated examples is the language's own unlabelled_examples setting.
configure_calibration(Lang, s(T, none, Sl, Su, TPos, TNeg, TGen, TS)) :-
    language(Lang, Script, _),
    loaded_script(Script),
    calibration(Lang, Exp),
    Head = experiment_output:setup_experiment(L, T0, Sl0, Su0, TP0, TN0, TG0, _),
    wrap_predicate(Head, aaai26_capture, _Inner,
                   (   current_prolog_flag(table_space, TS0),
                       throw(aaai26_captured(L, T0, Sl0, Su0, TP0, TN0, TG0, TS0))
                   )),
    catch(experiment_file:Exp,
          aaai26_captured(Lang1, T, Sl, Su, TPos, TNeg, TGen, TS),
          true),
    unwrap_predicate(experiment_output:setup_experiment/8, aaai26_capture),
    must_be(oneof([Lang]), Lang1),
    set_prolog_flag(table_space, TS),
    experiment_output:set_configs(Lang).

%!  iteration(+Settings, +I, -Spec) is det.
%
%   Spec is the labelled-example specification of the I-th iteration of the
%   range: the I-th element of test_harness:expanded_range/2 of it.
iteration(s(_, _, Sl, _, _, _, _, _), I, Spec) :-
    test_harness:expanded_range(Sl, Specs),
    nth1(I, Specs, Spec).

iterations(s(_, _, Sl, _, _, _, _, _), N) :-
    test_harness:expanded_range(Sl, Specs),
    length(Specs, N).

generated_range(s(_, Gs, _, _, _, _, _, _), Ks) :-
    test_harness:range_interval(Gs, Ks).

%!  problem(+Settings, +Spec, +Seed, -Labelled, -BK, -Metarules) is det.
%
%   The labelled examples as the repository generates them under Seed, with
%   the background knowledge and metarules of the target.
problem(s(T, _, _, Su, _, _, _, _), Spec, Seed, Ls, BK, MS) :-
    must_be(oneof([[]]), Su),
    set_random(seed(Seed)),
    language_generation:generate_initial(Spec, T, Ls),
    poker_auxiliaries:experiment_data(T, _, _, BK, MS).

% ---------- timing ----------

%!  timed(:Goal, +Limit, -Status, -Cost) is det.
%
%   Status is ok, failed, timeout or error(E); Cost is
%   cost(CpuMs, WallMs, Inferences).
timed(Goal, Limit, Status, cost(Cpu, Wall, Inf)) :-
    garbage_collect,
    statistics(cputime, C0),
    statistics(inferences, I0),
    get_time(W0),
    catch(call_with_time_limit(Limit,
                               (   call(Goal)
                               ->  Status = ok
                               ;   Status = failed
                               )),
          E,
          (   E == time_limit_exceeded
          ->  Status = timeout
          ;   Status = error(E)
          )),
    get_time(W1),
    statistics(inferences, I1),
    statistics(cputime, C1),
    Cpu is round((C1 - C0) * 1000000) / 1000,
    Wall is round((W1 - W0) * 1000000) / 1000,
    Inf is I1 - I0,
    (   Status == ok
    ->  true
    ;   abolish_all_tables
    ).

% ---------- the generalisation step ----------

%!  with_problem(+Labelled, +BK, +Metarules, -Encapsulated, :Goal)
%
%   Run Goal with the problem written as Poker's top_program/7 writes it:
%   the background knowledge, and the labelled examples too at clause limit
%   1, with Vanilla's tables refreshed.
with_problem(Ls, BK, MS, p(Ls_, MS_), Goal) :-
    mil_problem:encapsulated_problem(Ls, [], BK, MS, [Ls_, _, BK_, MS_]),
    poker_configuration:clause_limit(K),
    (   K =< 1
    ->  Bs = [Ls_, BK_]
    ;   Bs = [BK_]
    ),
    setup_call_cleanup(
        ( auxiliaries:write_problem(user, Bs, Refs),
          vanilla:refresh_tables(untable),
          vanilla:refresh_tables(table) ),
        Goal,
        ( auxiliaries:erase_program_clauses(Refs),
          vanilla:refresh_tables(untable) )).

poker_generalise(p(Ls_, MS_), Limit, Out, St, Cost) :-
    vanilla:refresh_tables(untable),
    vanilla:refresh_tables(table),
    timed(poker:generalise(Ls_, MS_, Out), Limit, St, Cost).

forest_generalise(p(Ls_, MS_), Limit, Out, St, Cost) :-
    timed(forest_poker:forest_generalise(Ls_, MS_, Out), Limit, St, Cost).

% Poker's generalise/3 fails when no example has a refutation within the
% clause limit (its sort of the empty list fails), and so does the forest's.
verdict(ok, P, ok, F, V) :- !,
    (   P =@= F
    ->  V = identical
    ;   V = different
    ).
verdict(failed, _, failed, _, both_failed) :- !.
verdict(PSt, _, FSt, _, not_compared(PSt, FSt)).

out_size(ok, Out, N) :- !, length(Out, N).
out_size(_, _, -).

command(settings, [LangA]) :-
    atom_to_term(LangA, Lang, _),
    configure(Lang, S),
    iterations(S, N),
    generated_range(S, Ks),
    poker_configuration:clause_limit(K),
    poker_configuration:max_invented(M),
    poker_configuration:unfold_invented(U),
    configuration:fetch_clauses(Fetch),
    configuration:table_meta_interpreter(Tab),
    findall(I-Spec, ( between(1, N, I), iteration(S, I, Spec) ), Its),
    format("~q.~n", [settings(Lang, S)]),
    format("~q.~n", [options(Lang, clause_limit(K), max_invented(M),
                             unfold_invented(U), fetch_clauses(Fetch),
                             table_meta_interpreter(Tab), generated(Ks),
                             iterations(Its))]).

command(gen, [LangA, IA, SeedsA, LimitA]) :-
    maplist([A, T]>>atom_to_term(A, T, _),
            [LangA, IA, SeedsA, LimitA], [Lang, I, Seeds, Limit]),
    configure_source(Lang, I, S),
    forall(( spec(S, I, I1, Spec), member(Seed, Seeds) ),
           gen_row(Lang, S, I1, Spec, Seed, Limit)).

% configure_source(+Lang, +I, -Settings): configure Lang from its calibration
% experiment when I is calibration, else from its range experiment.
configure_source(Lang, calibration, S) :- !,
    configure_calibration(Lang, S).
configure_source(Lang, _, S) :-
    configure(Lang, S).

% spec(+Settings, +I, -I1, -Spec): the labelled-example specification Spec of
% iteration I1 of the range: I1 is I, or every iteration when I is all; with
% I calibration, the calibration experiment's.
spec(s(_, _, Sl, _, _, _, _, _), calibration, calibration, Sl) :- !.
spec(S, I, I1, Spec) :-
    selected_iteration(S, I, I1),
    iteration(S, I1, Spec).

% selected_iteration(+Settings, +I, -I1): I1 is I, every iteration when I is
% all, the last when I is last, and each of a list.
selected_iteration(S, all, I1) :- !,
    iterations(S, N),
    between(1, N, I1).
selected_iteration(S, last, N) :- !,
    iterations(S, N).
selected_iteration(S, Is, I1) :-
    is_list(Is), !,
    member(I, Is),
    selected_iteration(S, I, I1).
selected_iteration(_, I, I).

% generated(+Settings, +G, -K): K is G, or the least or greatest number of
% generated examples of the range when G is min or max, the language's own
% unlabelled_examples setting when G is own, and each of a list.
generated(S, Gs, K) :-
    is_list(Gs), !,
    member(G, Gs),
    generated(S, G, K).
generated(_, own, K) :- !,
    poker_configuration:unlabelled_examples(K).
generated(S, min, K) :- !,
    generated_range(S, Ks),
    min_list(Ks, K).
generated(S, max, K) :- !,
    generated_range(S, Ks),
    max_list(Ks, K).
generated(_, K, K).

% her_limit(+Limit, -K, -M): her for the language's own clause_limit and
% max_invented, her+N for N more of each.
her_limits(her, K, M) :- !,
    poker_configuration:clause_limit(K),
    poker_configuration:max_invented(M).
her_limits(her+N, K, M) :- !,
    her_limits(her, K0, M0),
    K is K0 + N,
    M is M0 + N.

gen_row(Lang, S, I, Spec, Seed, Limit) :-
    forest_poker:use_vanilla,
    problem(S, Spec, Seed, Ls, BK, MS),
    length(Ls, NL),
    with_problem(Ls, BK, MS, Pb,
                 ( poker_generalise(Pb, Limit, P, PSt, PC),
                   forest_generalise(Pb, Limit, F, FSt, FC) )),
    out_size(PSt, P, PN),
    out_size(FSt, F, FN),
    verdict(PSt, P, FSt, F, V),
    format("~q.~n", [row(gen, Lang, I, Spec, Seed, NL,
                         poker(PSt, PN, PC), forest(FSt, FN, FC), V)]),
    flush_output.

% ---------- Poker's whole learn/7 ----------

%!  use_learner(+Mode, +Seed) is det.
%
%   Poker's generalise/3 is Vanilla's (Mode vanilla), the forest's (forest),
%   or read off one forest run at a larger limit (readoff, readoff_generalise/3).
%   Poker's generalisation draws one random number per refutation (a
%   Bernoulli trial of probability 1.0 that keeps every refutation); the
%   forest draws none. So that the steps after it (the order of the
%   generated examples) see the same random numbers, the generator is
%   reseeded after generalise/3 in every mode. The time spent in
%   generalise/3 is added to the global variable aaai26_gen_ms.
use_learner(Mode, Seed) :-
    forall(member(W, [aaai26_time, aaai26_reseed, aaai26_readoff]),
           (   unwrap_predicate(poker:generalise/3, W)
           ->  true
           ;   true
           )),
    (   Mode == forest
    ->  forest_poker:use_forest
    ;   forest_poker:use_vanilla
    ),
    (   Mode == readoff
    ->  wrap_predicate(poker:generalise(Pos, MS, Ss), aaai26_readoff, _,
                       aaai26_bench:readoff_generalise(Pos, MS, Ss))
    ;   true
    ),
    S1 is Seed + 1000003,
    wrap_predicate(poker:generalise(_, _, _), aaai26_reseed, W1,
                   ( W1, set_random(seed(S1)) )),
    wrap_predicate(poker:generalise(_, _, _), aaai26_time, W2,
                   aaai26_bench:timed_generalise(W2)).

timed_generalise(Goal) :-
    statistics(cputime, C0),
    (   call(Goal)
    ->  add_generalise_time(C0)
    ;   add_generalise_time(C0),
        fail
    ).

add_generalise_time(C0) :-
    statistics(cputime, C1),
    nb_getval(aaai26_gen_ms, A),
    A1 is A + (C1 - C0) * 1000,
    nb_setval(aaai26_gen_ms, A1).

%!  learn_once(+Mode, +Settings, +Spec, +Seed, +Limit, -Result) is det.
%
%   Result is learned(Status, Cost, Hypothesis, Positive, Negative, Eval,
%   GeneraliseMs).
learn_once(Mode, S, Spec, Seed, Limit,
           learned(St, Cost, Ps, Pos, Neg, Eval, GenMs)) :-
    use_learner(Mode, Seed),
    problem(S, Spec, Seed, Ls, BK, MS),
    nb_setval(aaai26_gen_ms, 0),
    timed(poker:learn(Ls, [], BK, MS, Pos, Neg, Ps), Limit, St, Cost),
    nb_getval(aaai26_gen_ms, GenMs0),
    GenMs is round(GenMs0 * 1000) / 1000,
    (   St == ok
    ->  evaluate(S, Spec, Seed, Ps, Pos, Neg, Eval)
    ;   Eval = none
    ).

%!  evaluate(+Settings, +Spec, +Seed, +Hypothesis, +Pos, +Neg, -Eval)
%
%   The repository's evaluation of a learned hypothesis: as an acceptor of
%   the testing examples (test_program/6), as a generator (test_generated/5)
%   and of the labelling (test_labelling/4). Eval is
%   eval(Acc, TPR, TNR, GenAcc, LabAcc). The testing examples are sampled
%   under a seed derived from Seed, the same in every mode.
evaluate(s(T, _, _, _, TPos, TNeg, TGen, _), Spec, Seed, Ps, Pos, Neg,
         eval(Acc, TPR, TNR, GenAcc, LabAcc)) :-
    S2 is Seed + 2000003,
    set_random(seed(S2)),
    test_harness:test_target(Spec, Sl_),
    test_harness:test_program(Sl_, T, Ps, TPos, TNeg, _-[Acc, _, TPR, TNR|_]),
    test_harness:test_generated(Sl_, T, TGen, Ps, GenAcc),
    test_harness:test_labelling(Sl_, Pos, Neg, _-[LabAcc|_]).

command(learn, [LangA, IA, GenA, SeedsA, LimitA]) :-
    maplist([A, T]>>atom_to_term(A, T, _),
            [LangA, IA, GenA, SeedsA, LimitA], [Lang, I, Gen, Seeds, Limit]),
    configure_source(Lang, I, S),
    forall(( generated(S, Gen, K), spec(S, I, I1, Spec), member(Seed, Seeds) ),
           (   poker_auxiliaries:set_poker_configuration_option(
                   unlabelled_examples, [K]),
               learn_row(Lang, S, I1, K, Spec, Seed, Limit)
           )).

learn_row(Lang, S, I, Gen, Spec, Seed, Limit) :-
    learn_once(vanilla, S, Spec, Seed, Limit, RV),
    learn_once(forest, S, Spec, Seed, Limit, RF),
    RV = learned(VSt, VC, VPs, VPos, VNeg, VEv, VG),
    RF = learned(FSt, FC, FPs, FPos, FNeg, FEv, FG),
    (   VSt == ok, FSt == ok
    ->  (   VPs =@= FPs, VPos =@= FPos, VNeg =@= FNeg
        ->  V = identical
        ;   V = different
        )
    ;   V = not_compared(VSt, FSt)
    ),
    hyp_size(VSt, VPs, VN),
    hyp_size(FSt, FPs, FN),
    format("~q.~n", [row(learn, Lang, I, Spec, Seed, Gen,
                         vanilla(VSt, VN, VC, VG, VEv),
                         forest(FSt, FN, FC, FG, FEv), V)]),
    (   V == different
    ->  format("~q.~n", [hypotheses(vanilla(VPs), forest(FPs))])
    ;   true
    ),
    (   VSt == ok
    ->  format("~q.~n", [hypothesis(Lang, I, Seed, Gen, VPs)])
    ;   true
    ),
    flush_output.

hyp_size(ok, Ps, N) :- !, length(Ps, N).
hyp_size(_, _, -).

% ---------- smaller limits read off one forest run ----------

set_limits(K, M) :-
    poker_auxiliaries:set_poker_configuration_option(clause_limit, [K]),
    poker_auxiliaries:set_poker_configuration_option(max_invented, [M]).

with_limits(K, M, Goal) :-
    poker_configuration:clause_limit(K0),
    poker_configuration:max_invented(M0),
    setup_call_cleanup(set_limits(K, M), Goal, set_limits(K0, M0)).

%!  readoff_generalise(+Pos, +Metarules, -Generalised) is det.
%
%   generalise/3 at the current clause limit K and max_invented M, read off
%   the last forest family computed for Pos if its limits cover (K, M), else
%   off a new family computed at (K, max(M, K-1)). At clause limit 1 Poker
%   writes the labelled examples as background knowledge, so the forest runs
%   directly there.
readoff_generalise(Pos, MS, Ss) :-
    poker_configuration:clause_limit(K),
    poker_configuration:max_invented(M),
    (   K =< 1
    ->  forest_poker:forest_generalise(Pos, MS, Ss)
    ;   family_for(Pos, MS, K, M, Fam),
        forest_poker:forest_readoff(Fam, Pos, MS, Ss)
    ).

family_for(Pos, MS, K, M, Fam) :-
    (   nb_current(aaai26_family, fam(Pos0, Kc, Mc, Fam0)),
        Pos0 =@= Pos, K =< Kc, M =< Mc
    ->  Fam = Fam0
    ;   Mc is max(M, K - 1),
        with_limits(K, Mc, forest_poker:forest_family(Pos, MS, Fam)),
        nb_setval(aaai26_family, fam(Pos, K, Mc, Fam))
    ).

command(readoff, [LangA, IA, SeedsA, LimitA, KmaxA, MmaxA]) :-
    maplist([A, T]>>atom_to_term(A, T, _),
            [LangA, IA, SeedsA, LimitA, KmaxA, MmaxA],
            [Lang, I, Seeds, Limit, Kmax0, Mmax0]),
    configure_source(Lang, I, S),
    (   her_limits(Kmax0, Kmax, Mmax)
    ->  true
    ;   Kmax = Kmax0, Mmax = Mmax0
    ),
    forall(( spec(S, I, I1, Spec), member(Seed, Seeds) ),
           readoff_rows(Lang, S, I1, Spec, Seed, Limit, Kmax, Mmax)).

%   One forest family at (Kmax, Mmax); for every K in 2..Kmax and M in
%   0..Mmax, its read-off against the forest run directly at (K, M) and
%   against Poker's generalise/3 at (K, M). At K = 1 the read-off's grade-1
%   supports are compared with the forest's own at K = 1, where the labelled
%   examples are background knowledge too.
readoff_rows(Lang, S, I, Spec, Seed, Limit, Kmax, Mmax) :-
    forest_poker:use_vanilla,
    problem(S, Spec, Seed, Ls, BK, MS),
    set_limits(Kmax, Mmax),
    with_problem(Ls, BK, MS, p(Ls_, MS_),
        ( timed(forest_poker:forest_family(Ls_, MS_, Fam), Limit, FamSt, FamC),
          family_size(FamSt, Fam, FamN),
          format("~q.~n", [row(family, Lang, I, Seed, Kmax, Mmax,
                               family(FamSt, FamN, FamC))]),
          flush_output,
          (   FamSt == ok
          ->  forall(( between(2, Kmax, K), between(0, Mmax, M) ),
                     readoff_row(Lang, I, Seed, Limit, Fam, Ls_, MS_, K, M))
          ;   true
          ) )),
    (   FamSt == ok
    ->  clause_limit_one(Lang, I, Seed, Fam, Ls, BK, MS)
    ;   true
    ).

family_size(ok, Fam, N) :- !,
    aggregate_all(count, ( member(_-NHs, Fam), member(_, NHs) ), N).
family_size(_, _, -).

readoff_row(Lang, I, Seed, Limit, Fam, Ls_, MS_, K, M) :-
    set_limits(K, M),
    timed(forest_poker:forest_readoff(Fam, Ls_, MS_, R), Limit, RSt, RC),
    forest_generalise(p(Ls_, MS_), Limit, F, FSt, FC),
    poker_generalise(p(Ls_, MS_), Limit, P, PSt, PC),
    out_size(RSt, R, RN), out_size(FSt, F, FN), out_size(PSt, P, PN),
    verdict(RSt, R, FSt, F, V1),
    verdict(FSt, F, PSt, P, V2),
    format("~q.~n", [row(readoff, Lang, I, Seed, K, M,
                         readoff(RSt, RN, RC), forest(FSt, FN, FC),
                         poker(PSt, PN, PC), readoff_vs_forest(V1),
                         forest_vs_poker(V2))]),
    flush_output.

% At clause limit 1 Poker's top_program/7 writes the labelled examples as
% background knowledge. The grade-1 supports of the family (computed without
% them) are compared with the forest's supports at clause limit 1 with them.
clause_limit_one(Lang, I, Seed, Fam, Ls, BK, MS) :-
    set_limits(1, 0),
    findall(H, ( member(_-NHs, Fam), member(1-H, NHs) ), Hs0),
    sort(Hs0, Graded1),
    with_problem(Ls, BK, MS, p(Ls_, MS_),
                 findall(H, ( member(Ep, Ls_),
                              forest_poker:forest_supports(Ep, 1, MS_, Hs),
                              member(H, Hs) ), Direct0)),
    sort(Direct0, Direct),
    length(Graded1, N1), length(Direct, N2),
    (   Graded1 == Direct
    ->  V = same
    ;   V = differ
    ),
    format("~q.~n", [row(clause_limit_one, Lang, I, Seed,
                         family_grade_one(N1), direct(N2), V)]),
    flush_output.

% ---------- iterative deepening of the limits ----------

%!  candidates(+Kmax, -Candidates) is det.
%
%   The pairs K-M of clause limit and max_invented in the order of the
%   deepening: K from 1 to Kmax and, for each, M from 0 to K - 1 (a
%   hypothesis of K clauses defines at most K - 1 invented predicates).
candidates(Kmax, Cs) :-
    findall(K-M, ( between(1, Kmax, K), M1 is K - 1, between(0, M1, M) ), Cs).

%!  correct(+Status, +Eval) is semidet.
%
%   The learned hypothesis accepts every positive and rejects every negative
%   testing example of the experiment.
correct(ok, eval(Acc, _, _, _, _)) :-
    Acc =:= 1.

command(tune, [LangA, SeedsA, LimitA, KmaxA]) :-
    maplist([A, T]>>atom_to_term(A, T, _),
            [LangA, SeedsA, LimitA, KmaxA], [Lang, Seeds, Limit, Kmax0]),
    configure_calibration(Lang, S),
    (   her_limits(Kmax0, Kmax, _)
    ->  true
    ;   Kmax = Kmax0
    ),
    S = s(_, _, Spec, _, _, _, _, _),
    poker_configuration:unlabelled_examples(Gen),
    candidates(Kmax, Cs),
    forall(member(Seed, Seeds),
           tune_rows(Lang, S, calibration, Gen, Spec, Seed, Limit, Cs)).

tune_rows(Lang, S, I, Gen, Spec, Seed, Limit, Cs) :-
    forall(member(Mode, [vanilla, forest, readoff]),
           (   deepen(Mode, S, Spec, Seed, Limit, Cs, Steps, Found),
               steps_total(Steps, Total, GenTotal),
               maplist(step_summary, Steps, Summary),
               format("~q.~n", [row(tune, Lang, I, Spec, Seed, Gen, Mode,
                                    Found, total(Total, GenTotal), Summary)]),
               flush_output,
               assertz(tune_steps(Mode, Steps))
           )),
    tune_agreement(Lang, I, Seed, Gen),
    retractall(tune_steps(_, _)).

:- dynamic tune_steps/2.

deepen(Mode, S, Spec, Seed, Limit, Cs, Steps, Found) :-
    nb_setval(aaai26_family, none),
    deepen_(Cs, Mode, S, Spec, Seed, Limit, Steps, Found).

deepen_([], _, _, _, _, _, [], none).
deepen_([K-M|Cs], Mode, S, Spec, Seed, Limit, [Step|Steps], Found) :-
    set_limits(K, M),
    learn_once(Mode, S, Spec, Seed, Limit,
               learned(St, Cost, Ps, _, _, Eval, GenMs)),
    Step = step(K, M, St, Cost, GenMs, Ps, Eval),
    (   correct(St, Eval)
    ->  Steps = [],
        Found = found(K, M, Ps)
    ;   memberchk(St, [ok, failed])
    ->  deepen_(Cs, Mode, S, Spec, Seed, Limit, Steps, Found)
    ;   Steps = [],
        Found = stopped(K, M, St)
    ).

steps_total(Steps, Total, GenTotal) :-
    foldl([step(_, _, _, cost(C, _, _), G, _, _), T0-G0, T1-G1]>>
              ( T1 is T0 + C, G1 is G0 + G ),
          Steps, 0-0, Total0-GenTotal0),
    Total is round(Total0 * 1000) / 1000,
    GenTotal is round(GenTotal0 * 1000) / 1000.

step_summary(step(K, M, St, cost(C, _, _), G, Ps, Eval),
             s(K, M, St, C, G, N, Eval)) :-
    hyp_size(St, Ps, N).

% The three deepenings learn the same hypothesis at every candidate they
% both reach.
tune_agreement(Lang, I, Seed, Gen) :-
    tune_steps(vanilla, VS),
    tune_steps(forest, FS),
    tune_steps(readoff, RS),
    (   same_steps(VS, FS), same_steps(VS, RS)
    ->  V = identical
    ;   V = different
    ),
    format("~q.~n", [row(tune_agreement, Lang, I, Seed, Gen, V)]),
    flush_output.

same_steps([], _) :- !.
same_steps(_, []) :- !.
same_steps([step(K, M, St1, _, _, P1, _)|S1], [step(K, M, St2, _, _, P2, _)|S2]) :-
    (   St1 == ok, St2 == ok
    ->  P1 =@= P2
    ;   true
    ),
    same_steps(S1, S2).
